"""Regenerate thesis tables and plots from saved prediction artifacts."""
import argparse
from pathlib import Path
import csv
import json

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
RUN = ROOT / 'thesis/generated/ml_finalization_seed42'
OUT = ROOT / 'thesis/generated/revision_evidence'


def table(out, name, spec, header, rows, caption, label):
    content = [r'% Generated by scripts/build_revision_evidence.py.', r'\begin{table}[htbp]',
               r'\centering\small', r'\begin{tabular}{'+spec+'}', r'\toprule',
               header+r' \\', r'\midrule']
    content += [' & '.join(row)+r' \\' for row in rows]
    content += [r'\bottomrule', r'\end{tabular}', r'\caption{'+caption+'}',
                r'\label{'+label+'}', r'\end{table}']
    (out/name).write_text('\n'.join(content)+'\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--run-dir', type=Path, default=RUN)
    parser.add_argument('--output-dir', type=Path, default=OUT)
    args = parser.parse_args()
    run_dir, out = args.run_dir, args.output_dir
    if run_dir.resolve() != RUN and out.resolve() == OUT:
        parser.error('specify a separate --output-dir for a different run')
    out.mkdir(parents=True, exist_ok=True)
    data = np.load(run_dir/'datasets/dataset.npz', allow_pickle=False)
    with np.load(run_dir/'preprocessing/split_indices.npz', allow_pickle=False) as split:
        test_indices = split['test_indices']
    names = ['Noisy $01/10$', 'Noisy $00/11$', 'Random NPT mixed',
             'Random product mixed', 'Random pure plus noise', r'Noisy $\Psi^+$', r'Noisy $\Phi^+$']
    family_rows, audit = [], []
    results = {}
    for width in (10, 50):
        predictions = np.load(run_dir/f'predictions/predictions_nh_{width}.npz', allow_pickle=False)
        y, pred = predictions['y_true'], predictions['y_pred']
        ids = predictions['test_indices']
        if not np.array_equal(ids, test_indices) or not np.array_equal(y, data['y'][ids]):
            raise ValueError('Predictions do not match the recorded test split and labels.')
        metrics = json.loads((run_dir/f'metrics/per_model_nh_{width}.json').read_text())
        if not np.isclose(np.mean(y == pred), metrics['test_accuracy'], rtol=0, atol=1e-12):
            raise ValueError('Aggregate metrics do not match saved predictions.')
        results[width] = []
        for i, family in enumerate(data['family_names']):
            mask = data['family_ids'][ids] == i
            count = int(mask.sum())
            fp = int(np.sum(mask & (y == 0) & (pred == 1)))
            fn = int(np.sum(mask & (y == 1) & (pred == 0)))
            row = dict(width=width, family=str(family), n=count, fp=fp, fn=fn,
                       accuracy=float(np.mean(y[mask] == pred[mask])))
            results[width].append(row)
            audit.append(row)
    for i, name in enumerate(names):
        a, b = results[10][i], results[50][i]
        family_rows.append([name, str(a['n']), f"{100*a['accuracy']:.2f}\\%", str(a['fp']), str(a['fn']),
                            f"{100*b['accuracy']:.2f}\\%", str(b['fp']), str(b['fn'])])
    table(out, 'family_table.tex', 'lrrrrrrr',
          r'Family & $N$ & Acc. (10) & FP & FN & Acc. (50) & FP & FN',
          family_rows, 'Held-out results by generating family. Each width has an accuracy and two error counts. '
          'The random NPT and product families each contain only one class.', 'tab:family-results')
    seed = json.loads((run_dir/'metrics/seed_robustness.json').read_text())
    rows = []
    for width in (0, 10, 50):
        a = seed['aggregate'][str(width)]['accuracy']
        rows.append([str(width), f"{100*a['mean']:.3f}\\%", f"{100*a['sample_standard_deviation']:.3f}",
                     ', '.join(f'{100*x:.3f}' for x in a['values'])])
    table(out, 'seed_table.tex', 'rrrr', r'$N_h$ & Mean accuracy & SD (pp) & Accuracies (\%)', rows,
          'Three model seeds, in order 42, 7 and 2026. Dataset, split and preprocessing remain fixed. '
          'SD is the sample standard deviation in percentage points.', 'tab:seed-results')
    with (run_dir/'metrics/noisy_bell_benchmark_metrics.csv').open() as stream:
        ble = {int(row['hidden_neurons']): row for row in csv.DictReader(stream)}
    rows = [[str(w), f"{float(ble[w]['p_star']):.3f}", f"{float(ble[w]['p_star_interpolated']):.6f}",
             f"{float(ble[w]['p_star_error']):.6f}", f"{float(ble[w]['ble']):.6f}"] for w in (0, 10, 50)]
    table(out, 'ble_table.tex', 'rrrrr', r'$N_h$ & $p_{\mathrm{grid}}$ & $\widehat p_\ast$ & Grid BLE & Interpolated BLE',
          rows, 'Two estimates of the same transition using grid spacing $10^{-3}$. '
          'Interpolation estimates a root within the selected bracket.', 'tab:ble-resolution')
    (out/'family_metrics.json').write_text(json.dumps(audit, indent=2)+'\n')
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    grid = np.genfromtxt(run_dir/'metrics/noisy_bell_benchmark.csv', delimiter=',', names=True)
    fig, ax = plt.subplots(figsize=(7.2, 4.1), layout='constrained')
    for width in (0, 10, 50):
        ax.plot(grid['p'], grid[f'prob_entangled_Nh{width}'], label=f'{width} hidden neurons')
    ax.axvline(1/3, color='0.3', linestyle='--', label='PPT threshold')
    ax.axhline(.5, color='0.5', linestyle=':', linewidth=.8)
    ax.set(xlabel='Bell-state mixing weight p', ylabel='Classifier score', xlim=(.25,.5), ylim=(-.02,1.02))
    ax.legend(frameon=False)
    fig.savefig(out/'noisy_bell_scores.png', dpi=220)
    plt.close(fig)
    print(f'Wrote verified family, seed and BLE tables and score plot to {out}')


if __name__ == '__main__':
    main()
